import { expect, test } from '@playwright/test'

test('desktop working timer survives renderer recycling and finish collapses the full process', async ({ page }) => {
    await page.goto('/e2e-fixtures/process-fixture.html')
    await page.getByRole('button', { name: 'Start working', exact: true }).click()
    const status = page.getByTestId('working-status')
    await expect(status).toHaveText(/Working for 2m \d+s/)
    await expect(page.getByText('I am checking the implementation.')).toBeVisible()
    const toggle = page.getByTestId('process-card-toggle')
    await toggle.click()
    await expect(page.getByText('Reasoning detail A')).toBeVisible()
    await page.getByRole('button', { name: 'Recycle', exact: true }).click()
    await page.getByRole('button', { name: 'Restore', exact: true }).click()
    await expect(status).toHaveText(/Working for 2m \d+s/)
    await page.getByRole('button', { name: 'Finish', exact: true }).click()
    await expect(status).toHaveCount(0)
    await expect(toggle).toHaveText('Worked for 2m 11s›')
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByText('I am checking the implementation.')).toHaveCount(0)
    await expect(page.getByText('Final answer remains visible.')).toBeVisible()
    const shell = page.locator('[data-hapi-process-card]')
    expect(await shell.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
    await toggle.click()
    await expect(page.getByText('I am checking the implementation.')).toBeVisible()
    await expect(page.getByText('Final answer remains visible.')).toBeVisible()
})

test('process card is closed by default and preserves decisions across stream, prepend and recycling', async ({ page }) => {
    await page.goto('/e2e-fixtures/process-fixture.html')
    const toggle = page.getByTestId('process-card-toggle')
    await expect(toggle).toHaveCount(1)
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByText('Final answer remains visible.')).toBeVisible()
    await expect(page.getByText('Reasoning detail A')).toHaveCount(0)
    await page.getByRole('button', { name: 'Stream', exact: true }).click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByText('New streamed reasoning')).toHaveCount(0)
    await toggle.click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await expect(page.getByText('Reasoning detail A')).toBeVisible()
    await expect(page.getByText('New streamed reasoning')).toBeVisible()
    await page.getByRole('button', { name: 'Prepend', exact: true }).click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await expect(page.getByText('Older reasoning')).toBeVisible()
    await page.getByRole('button', { name: 'Recycle', exact: true }).click()
    await expect(toggle).toHaveCount(0)
    await page.getByRole('button', { name: 'Restore', exact: true }).click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await toggle.click()
    await expect(page.getByTestId('process-card-content')).toHaveCount(0)
    await page.getByRole('button', { name: 'Other session', exact: true }).click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await toggle.focus()
    await page.keyboard.press('Enter')
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
})

test('mobile width keeps the final answer visible without horizontal overflow', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e-fixtures/process-fixture.html')
    await expect(page.getByTestId('process-card-toggle')).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByText('Final answer remains visible.')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
